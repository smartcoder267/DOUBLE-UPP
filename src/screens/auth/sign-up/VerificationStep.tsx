import React from 'react';
import { Pressable, StyleSheet, Text, View } from 'react-native';
import { Feather } from '@expo/vector-icons';
import { PrimaryButton } from '../../../components/common/PrimaryButton';
import { VerificationCodeInput } from '../../../components/forms/VerificationCodeInput';
import { colors, radii, spacing } from '../../../theme/tokens';

type VerificationStepProps = {
  destination: string;
  code: string;
  error?: string;
  loading?: boolean;
  onCodeChange: (value: string) => void;
  onContinue: () => void;
  onResend: () => void;
};

export function VerificationStep({ destination, code, error, loading = false, onCodeChange, onContinue, onResend }: VerificationStepProps) {
  return (
    <View style={styles.container}>
      <View style={styles.iconCircle}><Feather name="smartphone" size={25} color={colors.red[600]} /></View>
      <Text style={styles.helper}>A six-digit prototype code is ready for</Text>
      <Text style={styles.destination}>{destination}</Text>
      <VerificationCodeInput value={code} onChange={onCodeChange} error={error} />
      <PrimaryButton label="Confirm mobile number" onPress={onContinue} loading={loading} style={styles.button} />
      <Pressable accessibilityRole="button" disabled={loading} onPress={onResend} style={styles.resendButton}>
        <Text style={styles.resendText}>Code expired? <Text style={styles.resendStrong}>Generate another</Text></Text>
      </Pressable>
      <Text style={styles.previewNote}>Prototype only: the code is generated by the backend and autofilled here. This does not verify control of the SIM. FCM delivery will replace this autofill later.</Text>
    </View>
  );
}

const styles = StyleSheet.create({
  container: { gap: spacing.lg },
  iconCircle: { width: 52, height: 52, borderRadius: radii.lg, backgroundColor: colors.red[50], alignItems: 'center', justifyContent: 'center' },
  helper: { color: colors.black[500], fontSize: 14, marginBottom: -spacing.md },
  destination: { color: colors.black[950], fontSize: 16, fontWeight: '900' },
  button: { marginTop: spacing.sm },
  resendButton: { alignItems: 'center', paddingVertical: spacing.xs },
  resendText: { color: colors.black[500], fontSize: 13, fontWeight: '600' },
  resendStrong: { color: colors.red[600], fontWeight: '900' },
  previewNote: { color: colors.black[400], fontSize: 11, lineHeight: 17, textAlign: 'center' },
});
